def test_pg_ddl_identity_and_referential_constraints():
    ddl=postgres_ddl()
    assert 'PRAGMA' not in ddl
    assert 'COLLATE NOCASE' not in ddl
    assert 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in ddl
    assert 'student_id BIGINT NOT NULL REFERENCES users(id)' in ddl
    assert 'FOREIGN KEY' not in ddl  # inline typed REFERENCES are used
    assert 'CREATE UNIQUE INDEX IF NOT EXISTS users_email_casefold_uq' in ddl
    assert 'ADD COLUMN IF NOT EXISTS shift' in ddl
    assert 'route_id BIGINT PRIMARY KEY REFERENCES routes(id)' in ddl


def test_pg_placeholder_conversion_last_insert_id(monkeypatch):
    class FakeCursor:
        rowcount=1
        def fetchone(self):return {'id':44}
    class FakeRaw:
        def __init__(self):self.queries=[]
        def execute(self,query,params):
            self.queries.append((query,params));return FakeCursor()
    monkeypatch.setitem(sys.modules,'psycopg',types.SimpleNamespace(IntegrityError=type('PgError',(Exception,),{})))
    raw=FakeRaw();db=PgConnection(raw)
    x=db.execute('INSERT INTO buses(label,plate,capacity) VALUES(?,?,?)',('Demo','DEMO-X',30))
    assert x.lastrowid==44
    assert raw.queries[-1][0].endswith('VALUES(%s,%s,%s) RETURNING id')
    db.execute('SELECT * FROM buses WHERE id=?',(44,))
    assert raw.queries[-1] == ('SELECT * FROM buses WHERE id=%s',(44,))
    db.execute('INSERT INTO route_fleet(route_id,bus_id,driver_id) VALUES(?,?,?) ON CONFLICT(route_id) DO UPDATE SET bus_id=excluded.bus_id',(1,2,3))
    assert 'RETURNING' not in raw.queries[-1][0]


